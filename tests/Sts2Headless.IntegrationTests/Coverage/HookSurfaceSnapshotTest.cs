using Sts2Headless.Runtime.Hooks;
using Xunit;

namespace Sts2Headless.IntegrationTests.Coverage;

// Snapshot lock-in for the AbstractModel hook surface — the
// After* / Before* / On* virtual methods that ModelHookPatcher
// instruments. When sts2 adds, removes, or renames a hook, this test
// surfaces the exact delta against a checked-in baseline.
//
// Why this matters: the patcher discovers hooks reflectively by name
// prefix. A new hook in sts2 will be silently instrumented (if a
// concrete subtype overrides it) without anyone noticing — meaning
// our "did this kind fire?" trigger axis just got new behaviour we
// never reviewed. Conversely, a removed hook means existing tests
// asserting on its appearance suddenly stop firing.
//
// Baseline file: known-abstract-model-hooks.txt (next to this source,
// committed to git). Hook NAMES only — names are public API surface
// any modder can enumerate, same posture as the *Id.Fallback.cs files
// listing card names. Signatures aren't checked: a parameter type
// change doesn't affect what the patcher discovers (it matches on
// name) and adds noise to the diff.
//
// Regenerating after intentional drift:
//   UPDATE_HOOK_SNAPSHOT=1 dotnet test \
//       tests/Sts2Headless.IntegrationTests/Sts2Headless.IntegrationTests.csproj \
//       --filter "FullyQualifiedName~HookSurfaceSnapshotTest"
// — the test writes the new baseline and passes; commit the diff with
// the change that justified it.
[Collection(InProcessSts2Collection.Name)]
public class HookSurfaceSnapshotTest : IClassFixture<ContentManifestFixture>
{
    private readonly ContentManifestFixture _f;
    public HookSurfaceSnapshotTest(ContentManifestFixture f) { _f = f; }

    private const string BaselineFileName = "known-abstract-model-hooks.txt";

    [Fact]
    public void AbstractModelHookSurface_MatchesSnapshot()
    {
        var liveHooks = ModelHookPatcher.EnumerateHookNames(_f.Sts2);
        var baselinePath = FindBaselinePath();

        if (Environment.GetEnvironmentVariable("UPDATE_HOOK_SNAPSHOT") == "1")
        {
            WriteBaseline(baselinePath, liveHooks);
            // Pass deliberately — caller asked to regenerate.
            return;
        }

        if (!File.Exists(baselinePath))
        {
            Assert.Fail(
                $"Baseline file missing at {baselinePath}. " +
                $"Generate it with: UPDATE_HOOK_SNAPSHOT=1 dotnet test --filter \"FullyQualifiedName~{nameof(HookSurfaceSnapshotTest)}\"");
        }

        var committed = ReadBaseline(baselinePath);
        var liveSet = new SortedSet<string>(liveHooks, StringComparer.Ordinal);
        var committedSet = new SortedSet<string>(committed, StringComparer.Ordinal);

        var added = liveSet.Except(committedSet, StringComparer.Ordinal)
            .OrderBy(s => s, StringComparer.Ordinal).ToList();
        var removed = committedSet.Except(liveSet, StringComparer.Ordinal)
            .OrderBy(s => s, StringComparer.Ordinal).ToList();

        if (added.Count == 0 && removed.Count == 0) return;

        var lines = new List<string>
        {
            "AbstractModel hook surface drifted from the committed snapshot.",
            "  If sts2 was bumped or a hook was intentionally added/removed, regenerate the baseline:",
            $"    UPDATE_HOOK_SNAPSHOT=1 dotnet test --filter \"FullyQualifiedName~{nameof(HookSurfaceSnapshotTest)}\"",
            "  then review the diff in the same PR as the change that motivated it.",
        };
        if (added.Count > 0)
            lines.Add($"  Added in sts2 (not in baseline): [{string.Join(", ", added)}]");
        if (removed.Count > 0)
            lines.Add($"  Removed from sts2 (in baseline): [{string.Join(", ", removed)}]");
        Assert.Fail(string.Join('\n', lines));
    }

    private static void WriteBaseline(string path, IReadOnlyList<string> hooks)
    {
        var content = string.Join('\n',
            new[] { "# AbstractModel hook surface — generated by HookSurfaceSnapshotTest.", "# Regenerate with UPDATE_HOOK_SNAPSHOT=1.", "" }
            .Concat(hooks)
            .Append("")) ;
        File.WriteAllText(path, content);
    }

    private static IReadOnlyList<string> ReadBaseline(string path)
    {
        var names = new List<string>();
        foreach (var raw in File.ReadAllLines(path))
        {
            var line = raw.Trim();
            if (line.Length == 0) continue;
            if (line.StartsWith('#')) continue;
            names.Add(line);
        }
        return names;
    }

    // The baseline lives next to this source file. AppContext.BaseDirectory
    // is the test bin dir; walk up until we find the repo root, then descend
    // into tests/Sts2Headless.IntegrationTests/Coverage/.
    private static string FindBaselinePath()
    {
        var dir = AppContext.BaseDirectory;
        for (var i = 0; i < 8; i++)
        {
            if (File.Exists(Path.Combine(dir, "Sts2Headless.slnx")))
            {
                return Path.Combine(dir, "tests", "Sts2Headless.IntegrationTests", "Coverage", BaselineFileName);
            }
            var parent = Directory.GetParent(dir);
            if (parent is null) break;
            dir = parent.FullName;
        }
        throw new InvalidOperationException("repo root not found from " + AppContext.BaseDirectory);
    }
}
